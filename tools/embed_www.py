# PlatformIO pre-build script: gzip everything in www/ into src/www_assets.h
# so the web UI ships inside the firmware image (one OTA update = firmware + UI).
import gzip, os

try:
    Import("env")  # noqa: F821  (provided by PlatformIO)
    PROJECT = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SRC = os.path.join(PROJECT, "www")
OUT = os.path.join(PROJECT, "src", "www_assets.h")
MIME = {".html": "text/html; charset=utf-8", ".js": "application/javascript", ".css": "text/css",
        ".svg": "image/svg+xml", ".woff2": "font/woff2", ".png": "image/png", ".ico": "image/x-icon",
        ".json": "application/json"}


def build():
    files = []
    for root, _, names in os.walk(SRC):
        for n in sorted(names):
            if n.startswith("."):
                continue
            full = os.path.join(root, n)
            rel = "/" + os.path.relpath(full, SRC).replace(os.sep, "/")
            files.append((rel, full))
    files.sort()
    lines = ["// Generated by tools/embed_www.py - do not edit", "#pragma once", "#include <Arduino.h>", "",
             "struct WwwAsset { const char *path; const char *mime; const uint8_t *data; size_t len; };", ""]
    entries = []
    total = 0
    for i, (rel, full) in enumerate(files):
        with open(full, "rb") as f:
            raw = f.read()
        gz = gzip.compress(raw, 9, mtime=0)
        total += len(gz)
        name = "WWW_%d" % i
        hexes = ",".join("0x%02x" % b for b in gz)
        lines.append("static const uint8_t %s[] PROGMEM = {%s};" % (name, hexes))
        mime = MIME.get(os.path.splitext(rel)[1], "application/octet-stream")
        entries.append('  {"%s", "%s", %s, %d},' % (rel, mime, name, len(gz)))
    lines.append("static const WwwAsset WWW_ASSETS[] = {")
    lines += entries
    lines.append("};")
    lines.append("static const size_t WWW_ASSET_COUNT = %d;" % len(entries))
    content = "\n".join(lines) + "\n"
    old = open(OUT).read() if os.path.exists(OUT) else ""
    if content != old:
        with open(OUT, "w") as f:
            f.write(content)
    print("embed_www: %d files, %d bytes gzipped" % (len(files), total))


build()
